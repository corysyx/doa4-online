"""Writes tests/host/doa4_tweak_fixtures.h (usage: patch.toml out.h): the Xenia Rev 1 patch bytes.

It reads only the patch file. The image's bytes at the patch sites are not kept in the repository: tweaks_host_test.cpp
chooses its own "original" bytes, and with DOA4_TEST_IMAGE set it reads the real ones from your own image (checked
against one SHA-1 over the sites in address order)."""
import sys, tomllib
patch_path, out_path = sys.argv[1:3]
doc = tomllib.load(open(patch_path, 'rb'))
want = {
    'All Stages Available in Tag Mode': 'kTagAllStages',
    'All Characters Unlocked': 'kMpHiddenCharacters',
    'Alpha-152 can now be selected!': 'kAlpha152',
}
out = ['// Generated by make_tweak_fixtures.py from the Xenia patch file',
       '// "544307D1 - DEAD OR ALIVE 4 (Rev1).patch.toml" (patches by ryu_highabusa), 2026-10-28.',
       "// Do not edit by hand. (The image's bytes at these addresses are not here: the tests read them from your own image.)", '',
       '#pragma once', '', '#include <cstdint>', '#include <vector>', '',
       'namespace doa4_fixtures {', '',
       'struct FixturePatch {', '  uint32_t address;', "  std::vector<uint8_t> on;  // the patch file's bytes", '};', '']
for p in doc['patch']:
    if p['name'] not in want: continue
    # tomllib groups be8 and array entries separately, so order by address
    items = []
    for e in p.get('be8', []): items.append((e['address'], bytes([e['value']])))
    for e in p.get('array', []): items.append((e['address'], bytes.fromhex(e['value'])))
    items.sort()
    out.append(f'// {p["name"]}')
    out.append(f'inline const std::vector<FixturePatch> {want[p["name"]]} = {{')
    f = lambda bs: '{' + ', '.join(f'0x{x:02X}' for x in bs) + '}'
    for a, b in items:
        out.append(f'    {{0x{a:08X}, {f(b)}}},')
    out.append('};')
    out.append('')
out.append('}  // namespace doa4_fixtures')
open(out_path, 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', out_path)
